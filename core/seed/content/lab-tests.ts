/**
 * Lab test and imaging catalogue (plan §7.1): about 150 laboratory tests
 * across haematology, biochemistry, immunology, serology, hormones, urine,
 * microbiology (template) and histopathology (template), plus the imaging
 * catalogue (X-ray, ultrasound, ECG, echo). Reference ranges and critical
 * limits are typical adult values written for the demo, with sex and age
 * bands where they matter. Demo data: not for clinical use.
 */

import type {
  Analyte,
  Container,
  LabSection,
  LabTestRow,
  Modality,
  RefRange,
} from "@/core/db/schema"

export type LabTestSeed = Omit<
  LabTestRow,
  | "id"
  | "version"
  | "createdAt"
  | "updatedAt"
  | "createdBy"
  | "updatedBy"
  | "origin"
  | "originAt"
> & { id: string }

/* ---------------- Range helpers ---------------- */

const r = (low?: number, high?: number): RefRange => ({ low, high })
const adultM = (low?: number, high?: number): RefRange => ({
  sex: "M",
  ageMinYears: 18,
  low,
  high,
})
const adultF = (low?: number, high?: number): RefRange => ({
  sex: "F",
  ageMinYears: 18,
  low,
  high,
})
const child = (
  low?: number,
  high?: number,
  ageMin = 1,
  ageMax = 18
): RefRange => ({ ageMinYears: ageMin, ageMaxYears: ageMax, low, high })
const q = (text = "Negative"): RefRange => ({ text })

function an(
  code: string,
  name: string,
  units: string | undefined,
  decimals: number,
  ranges: RefRange[],
  critical?: { low?: number; high?: number }
): Analyte {
  return {
    code,
    name,
    units,
    decimals,
    ranges,
    criticalLow: critical?.low,
    criticalHigh: critical?.high,
  }
}

function ql(code: string, name: string, normal = "Negative"): Analyte {
  return { code, name, decimals: 0, ranges: [q(normal)], qualitative: true }
}

type LabOpts = {
  method?: string
  sendOut?: boolean
  signatory?: LabTestRow["signatoryGroup"]
  template?: LabTestRow["template"]
}

function lab(
  id: string,
  code: string,
  name: string,
  glossBn: string | undefined,
  section: LabSection,
  specimen: LabTestRow["specimen"],
  container: Container,
  volumeMl: number,
  tatHours: number,
  stabilityHours: number,
  priceTaka: number,
  analytes: Analyte[],
  opts: LabOpts = {}
): LabTestSeed {
  return {
    id,
    code,
    name,
    glossBn,
    section,
    kind: "lab",
    specimen,
    container,
    volumeMl,
    method: opts.method,
    tatHours,
    analytes,
    stabilityHours,
    sendOut: opts.sendOut ?? false,
    signatoryGroup:
      opts.signatory ??
      (section === "microbiology" ? "microbiology" : "pathology"),
    priceP: priceTaka * 100,
    template: opts.template,
  }
}

function img(
  id: string,
  code: string,
  name: string,
  glossBn: string,
  modality: Modality,
  priceTaka: number,
  tatHours: number
): LabTestSeed {
  const cardiac = modality === "ecg" || modality === "echo"
  return {
    id,
    code,
    name,
    glossBn,
    section: cardiac ? "cardiology" : "imaging",
    kind: "imaging",
    modality,
    specimen: "none",
    container: "none",
    volumeMl: 0,
    tatHours,
    analytes: [],
    stabilityHours: 0,
    sendOut: false,
    signatoryGroup: cardiac ? "cardiology" : "radiology",
    priceP: priceTaka * 100,
  }
}

