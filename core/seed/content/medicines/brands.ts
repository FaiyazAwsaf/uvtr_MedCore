/* Pack helpers */
const s = (strips: number, per: number): PackSize => ({
  label: `${strips} x ${per} strip`,
  units: strips * per,
  stripSize: per,
})
const bottle = (ml: number): PackSize => ({
  label: `${ml} ml bottle`,
  units: 1,
})
const drops = (ml: number): PackSize => ({
  label: `${ml} ml dropper bottle`,
  units: 1,
})
const vial: PackSize = { label: "1 vial", units: 1 }
const amp = (n = 5): PackSize => ({ label: `${n} ampoules`, units: n })
const tube = (g: number): PackSize => ({ label: `${g} g tube`, units: 1 })
const inhaler = (doses: number): PackSize => ({
  label: `${doses}-dose inhaler`,
  units: 1,
})
const sachets = (n: number): PackSize => ({ label: `${n} sachets`, units: n })
const supp: PackSize = { label: "2 x 5 suppositories", units: 10, stripSize: 5 }

