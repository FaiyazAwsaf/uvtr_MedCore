/** Stable id from brand name, strength and (for non-oral-solids) the form. */
export function brandId(
  name: string,
  strength: string,
  form: DosageForm
): string {
  const slug = (v: string) => v.toLowerCase().replace(/[^a-z0-9]+/g, "")
  const solid = form === "tablet" || form === "capsule"
  return `brd_${slug(name)}_${slug(strength)}${solid ? "" : `_${form}`}`
}
